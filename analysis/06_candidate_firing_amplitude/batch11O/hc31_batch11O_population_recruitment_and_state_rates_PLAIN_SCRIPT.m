%% Main animal/epoch processing

epochNames = ["PRE","REST","POST","RUN1AWAKE"];
epochColumns = [1 3 4 2];

for animalPosition = 1:numel(animalIndices)
    resSaveIndex = animalIndices(animalPosition);

    if resSaveIndex > numel(resSave)
        continue
    end

    R = resSave(resSaveIndex);
    animalID = string(fallbackAnimalIDs{animalPosition});

    try
        if isfield(R,'spAll') && ...
                ~isempty(R.spAll) && ...
                isfield(R.spAll,'animal')
            animalID = strtrim(string(R.spAll(1).animal));
        elseif isfield(R,'name')
            animalID = strtrim(string(R.name));
        elseif isfield(R,'animal')
            animalID = strtrim(string(R.animal));
        end
    catch
    end

    fprintf('\nProcessing %s\n',animalID);

    for epochIndex = 1:numel(epochNames)
        epochName = epochNames(epochIndex);

        eventRows = find( ...
            Events.animal == animalID & ...
            Events.epoch == epochName);

        if isempty(eventRows)
            continue
        end

        [spikeCell,usableMask,nUnits,loadedColumn] = ...
            hc31_batch11O_load_epoch_spikes( ...
            R,epochName);

        usableUnits = find(usableMask);

        if isempty(usableUnits)
            fprintf('  %s: no usable spike data.\n',epochName);
            continue
        end

        fprintf('  %s: %d events, %d usable units, column %d\n', ...
            epochName, ...
            numel(eventRows), ...
            numel(usableUnits), ...
            loadedColumn);

        isBeta2Tagged = false(nUnits,1);
        isNovelTagged = false(nUnits,1);

        if ~isempty(UnitTags) && ...
                ~isempty(tagAnimalColumn) && ...
                ~isempty(tagUnitColumn)

            tagMask = ...
                strtrim(string( ...
                UnitTags.(tagAnimalColumn))) == ...
                animalID;

            TagSub = UnitTags(tagMask,:);

            if ~isempty(tagBandColumn) && ...
                    ~isempty(TagSub)
                bandText = lower(strtrim(string( ...
                    TagSub.(tagBandColumn))));

                betaBandMask = ...
                    contains(bandText,'beta2') | ...
                    contains(bandText,'23-30') | ...
                    contains(bandText,'23_30');

                if any(betaBandMask)
                    TagSub = TagSub(betaBandMask,:);
                end
            end

            if ~isempty(TagSub)
                unitValues = ...
                    str2double(string( ...
                    TagSub.(tagUnitColumn)));

                if isnumeric(TagSub.(tagUnitColumn))
                    unitValues = ...
                        double(TagSub.(tagUnitColumn));
                end

                betaValues = false(height(TagSub),1);
                novelValues = false(height(TagSub),1);

                if ~isempty(tagBetaColumn)
                    raw = TagSub.(tagBetaColumn);

                    if isnumeric(raw) || islogical(raw)
                        betaValues = logical(raw);
                    else
                        textValues = lower(strtrim(string(raw)));
                        betaValues = ...
                            textValues == "true" | ...
                            textValues == "1" | ...
                            textValues == "yes";
                    end
                end

                if ~isempty(tagNovelColumn)
                    raw = TagSub.(tagNovelColumn);

                    if isnumeric(raw) || islogical(raw)
                        novelValues = logical(raw);
                    else
                        textValues = lower(strtrim(string(raw)));
                        novelValues = ...
                            textValues == "true" | ...
                            textValues == "1" | ...
                            textValues == "yes";
                    end
                end

                for tagIndex = 1:numel(unitValues)
                    unitIndex = round(unitValues(tagIndex));

                    if isfinite(unitIndex) && ...
                            unitIndex >= 1 && ...
                            unitIndex <= nUnits
                        isBeta2Tagged(unitIndex) = ...
                            isBeta2Tagged(unitIndex) | ...
                            betaValues(tagIndex);

                        isNovelTagged(unitIndex) = ...
                            isNovelTagged(unitIndex) | ...
                            novelValues(tagIndex);
                    end
                end

                isBeta2Tagged = ...
                    isBeta2Tagged | isNovelTagged;
            end
        end

        % Build same-state pseudo-event pools for sleep epochs.
        pseudoPools = struct();

        if epochName ~= "RUN1AWAKE"
            stateNamesThisEpoch = unique( ...
                Events.operationalStateAtPeak(eventRows), ...
                'stable');

            allEpochPeaks = double( ...
                Master.peakUs( ...
                Master.animal == animalID & ...
                Master.epoch == epochName));

            for stateIndex = 1:numel(stateNamesThisEpoch)
                stateName = stateNamesThisEpoch(stateIndex);

                windowMask = ...
                    StateWindows.animal == animalID & ...
                    StateWindows.epoch == epochName & ...
                    StateWindows.operationalState == stateName & ...
                    ~logical( ...
                    StateWindows.isArtefactOrUnusable);

                candidateCenters = double( ...
                    StateWindows.windowCenterUs(windowMask));

                keepCenters = true(size(candidateCenters));

                for centerIndex = 1:numel(candidateCenters)
                    if any(abs( ...
                            allEpochPeaks- ...
                            candidateCenters(centerIndex)) <= ...
                            pseudoExclusionSec*1e6)
                        keepCenters(centerIndex) = false;
                    end
                end

                candidateCenters = ...
                    candidateCenters(keepCenters);

                if ~isempty(candidateCenters)
                    candidateCenters = ...
                        candidateCenters( ...
                        randperm(numel(candidateCenters)));
                end

                fieldName = matlab.lang.makeValidName( ...
                    char(stateName));

                pseudoPools.(fieldName) = candidateCenters;
            end
        end

        pseudoPoolCounters = struct();

        for localEventIndex = 1:numel(eventRows)
            rowIndex = eventRows(localEventIndex);
            peakUs = double(Events.peakUs(rowIndex));

            centralCounts = zeros(nUnits,1);
            leftCounts = zeros(nUnits,1);
            rightCounts = zeros(nUnits,1);
            pethCounts = zeros(nUnits,nBins);

            for unitIndex = usableUnits(:)'
                spikeTimes = spikeCell{unitIndex};
                relativeSec = ...
                    (spikeTimes-peakUs)/1e6;

                pethMask = ...
                    relativeSec >= -pethHalfWindowSec & ...
                    relativeSec < pethHalfWindowSec;

                if any(pethMask)
                    pethCounts(unitIndex,:) = histcounts( ...
                        relativeSec(pethMask), ...
                        pethEdges);
                end

                centralCounts(unitIndex) = sum( ...
                    relativeSec >= centralWindow(1) & ...
                    relativeSec < centralWindow(2));

                leftCounts(unitIndex) = sum( ...
                    relativeSec >= leftFlankWindow(1) & ...
                    relativeSec < leftFlankWindow(2));

                rightCounts(unitIndex) = sum( ...
                    relativeSec >= rightFlankWindow(1) & ...
                    relativeSec < rightFlankWindow(2));
            end

            flankCounts = leftCounts+rightCounts;
            nUsable = numel(usableUnits);

            nUsableUnits(rowIndex) = nUsable;

            centralRateHzPerUnit(rowIndex) = ...
                sum(centralCounts(usableUnits)) / ...
                (nUsable*centralDurationSec);

            flankRateHzPerUnit(rowIndex) = ...
                sum(flankCounts(usableUnits)) / ...
                (nUsable*flankDurationSec);

            centralMinusFlankRate(rowIndex) = ...
                centralRateHzPerUnit(rowIndex)- ...
                flankRateHzPerUnit(rowIndex);

            centralActiveFraction(rowIndex) = ...
                mean(centralCounts(usableUnits) >= 1);

            flankActiveFraction(rowIndex) = mean([ ...
                mean(leftCounts(usableUnits) >= 1), ...
                mean(rightCounts(usableUnits) >= 1)]);

            centralMinusFlankActiveFraction(rowIndex) = ...
                centralActiveFraction(rowIndex)- ...
                flankActiveFraction(rowIndex);

            eventPethRate(rowIndex,:) = ...
                sum(pethCounts(usableUnits,:),1) / ...
                (nUsable*pethBinSec);

            taggedMask = usableMask & isBeta2Tagged;
            untaggedMask = usableMask & ~isBeta2Tagged;
            novelMask = usableMask & isNovelTagged;

            if any(taggedMask)
                beta2TaggedNUnits(rowIndex) = sum(taggedMask);

                taggedCentral = ...
                    sum(centralCounts(taggedMask)) / ...
                    (sum(taggedMask)*centralDurationSec);

                taggedFlank = ...
                    sum(flankCounts(taggedMask)) / ...
                    (sum(taggedMask)*flankDurationSec);

                beta2TaggedCentralMinusFlankRate(rowIndex) = ...
                    taggedCentral-taggedFlank;
            end

            if any(untaggedMask)
                untaggedNUnits(rowIndex) = sum(untaggedMask);

                untaggedCentral = ...
                    sum(centralCounts(untaggedMask)) / ...
                    (sum(untaggedMask)*centralDurationSec);

                untaggedFlank = ...
                    sum(flankCounts(untaggedMask)) / ...
                    (sum(untaggedMask)*flankDurationSec);

                untaggedCentralMinusFlankRate(rowIndex) = ...
                    untaggedCentral-untaggedFlank;
            end

            if any(novelMask)
                novelBeta2TaggedNUnits(rowIndex) = sum(novelMask);

                novelCentral = ...
                    sum(centralCounts(novelMask)) / ...
                    (sum(novelMask)*centralDurationSec);

                novelFlank = ...
                    sum(flankCounts(novelMask)) / ...
                    (sum(novelMask)*flankDurationSec);

                novelBeta2TaggedCentralMinusFlankRate(rowIndex) = ...
                    novelCentral-novelFlank;
            end

            % State-matched pseudo-event control for sleep epochs.
            if epochName ~= "RUN1AWAKE"
                stateName = ...
                    Events.operationalStateAtPeak(rowIndex);

                fieldName = matlab.lang.makeValidName( ...
                    char(stateName));

                if isfield(pseudoPools,fieldName)
                    pool = pseudoPools.(fieldName);

                    if ~isempty(pool)
                        if ~isfield(pseudoPoolCounters,fieldName)
                            pseudoPoolCounters.(fieldName) = 1;
                        end

                        poolIndex = ...
                            pseudoPoolCounters.(fieldName);

                        if poolIndex > numel(pool)
                            poolIndex = ...
                                mod(poolIndex-1,numel(pool))+1;
                        end

                        controlUs = pool(poolIndex);
                        pseudoPoolCounters.(fieldName) = ...
                            poolIndex+1;
                        pseudoPeakUs(rowIndex) = controlUs;

                        controlCentralCounts = zeros(nUnits,1);
                        controlPethCounts = zeros(nUnits,nBins);

                        for unitIndex = usableUnits(:)'
                            spikeTimes = spikeCell{unitIndex};
                            relativeSec = ...
                                (spikeTimes-controlUs)/1e6;

                            pethMask = ...
                                relativeSec >= ...
                                    -pethHalfWindowSec & ...
                                relativeSec < ...
                                    pethHalfWindowSec;

                            if any(pethMask)
                                controlPethCounts(unitIndex,:) = ...
                                    histcounts( ...
                                    relativeSec(pethMask), ...
                                    pethEdges);
                            end

                            controlCentralCounts(unitIndex) = ...
                                sum( ...
                                relativeSec >= ...
                                    centralWindow(1) & ...
                                relativeSec < ...
                                    centralWindow(2));
                        end

                        pseudoCentralRateHzPerUnit(rowIndex) = ...
                            sum(controlCentralCounts(usableUnits)) / ...
                            (nUsable*centralDurationSec);

                        pseudoCentralActiveFraction(rowIndex) = ...
                            mean( ...
                            controlCentralCounts(usableUnits) >= 1);

                        eventMinusPseudoRate(rowIndex) = ...
                            centralRateHzPerUnit(rowIndex)- ...
                            pseudoCentralRateHzPerUnit(rowIndex);

                        eventMinusPseudoActiveFraction(rowIndex) = ...
                            centralActiveFraction(rowIndex)- ...
                            pseudoCentralActiveFraction(rowIndex);

                        pseudoPethRate(rowIndex,:) = ...
                            sum(controlPethCounts(usableUnits,:),1) / ...
                            (nUsable*pethBinSec);
                    end
                end
            end
        end
    end
end

