%% HC-31 Batch 11O
% VALIDATED CA1 POPULATION RECRUITMENT AND STATE-MATCHED EVENT RATES
%
% Plain script: no local functions.
%
% Primary questions:
% 1. Do locked candidate-event tiers coincide with increased CA1 population
%    firing relative to equal-duration flanks?
% 2. Does recruitment exceed state-matched pseudo-event recruitment?
% 3. How do screened event rates differ across PRE, REST and POST when the
%    operational LFP state is matched?
% 4. Are conclusions stable across Tier A, A+B, A+C and A+B+C definitions?
%
% Inference is animal-weighted. Event-level rows are retained for audit, but
% event counts are not treated as independent biological replicates.

