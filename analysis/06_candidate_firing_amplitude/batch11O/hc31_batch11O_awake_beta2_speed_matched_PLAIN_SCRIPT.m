        'controlPreBurstFraction', ...
        'controlPostBurstFraction', ...
        'controlPeakEnvelopeZ'};

    for metricIndex = 1:numel(metricNames)
        PairTable.(metricNames{metricIndex}) = ...
            nan(height(PairTable),1);
    end

    eventPethZ = nan(height(PairTable),nBins);
    controlPethZ = nan(height(PairTable),nBins);
