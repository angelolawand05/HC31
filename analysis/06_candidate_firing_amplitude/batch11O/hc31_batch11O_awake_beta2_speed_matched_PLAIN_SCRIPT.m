            settings);

        PairTable.eventBeta2FailureReason(rowIndex) = ...
            EventBeta.failureReason;
        PairTable.controlBeta2FailureReason(rowIndex) = ...
            ControlBeta.failureReason;

        PairTable.eventBeta2EffectiveFs(rowIndex) = ...
            EventBeta.effectiveSamplingRateHz;
        PairTable.eventPreMeanZ(rowIndex) = ...
            EventBeta.preMeanZ;
        PairTable.eventCentralMeanZ(rowIndex) = ...
            EventBeta.centralMeanZ;
        PairTable.eventEarlyPostMeanZ(rowIndex) = ...
            EventBeta.earlyPostMeanZ;
        PairTable.eventLatePostMeanZ(rowIndex) = ...
            EventBeta.latePostMeanZ;
        PairTable.eventPostMinusPreZ(rowIndex) = ...
            EventBeta.postMinusPreZ;
        PairTable.eventCentralMinusPreZ(rowIndex) = ...
            EventBeta.centralMinusPreZ;
        PairTable.eventPreBurstCount(rowIndex) = ...
            EventBeta.preBurstCount;
        PairTable.eventPostBurstCount(rowIndex) = ...
            EventBeta.postBurstCount;
        PairTable.eventPreBurstFraction(rowIndex) = ...
            EventBeta.preBurstFraction;
        PairTable.eventPostBurstFraction(rowIndex) = ...
            EventBeta.postBurstFraction;
        PairTable.eventPeakEnvelopeZ(rowIndex) = ...
            EventBeta.peakEnvelopeZ;

        PairTable.controlBeta2EffectiveFs(rowIndex) = ...
            ControlBeta.effectiveSamplingRateHz;
        PairTable.controlPreMeanZ(rowIndex) = ...
            ControlBeta.preMeanZ;
        PairTable.controlCentralMeanZ(rowIndex) = ...
            ControlBeta.centralMeanZ;
        PairTable.controlEarlyPostMeanZ(rowIndex) = ...
            ControlBeta.earlyPostMeanZ;
        PairTable.controlLatePostMeanZ(rowIndex) = ...
            ControlBeta.latePostMeanZ;
        PairTable.controlPostMinusPreZ(rowIndex) = ...
            ControlBeta.postMinusPreZ;
        PairTable.controlCentralMinusPreZ(rowIndex) = ...
            ControlBeta.centralMinusPreZ;
        PairTable.controlPreBurstCount(rowIndex) = ...
            ControlBeta.preBurstCount;
        PairTable.controlPostBurstCount(rowIndex) = ...
            ControlBeta.postBurstCount;
        PairTable.controlPreBurstFraction(rowIndex) = ...
            ControlBeta.preBurstFraction;
        PairTable.controlPostBurstFraction(rowIndex) = ...
            ControlBeta.postBurstFraction;
        PairTable.controlPeakEnvelopeZ(rowIndex) = ...
            ControlBeta.peakEnvelopeZ;

        eventPethZ(rowIndex,:) = ...
            EventBeta.pethEnvelopeZ;

        controlPethZ(rowIndex,:) = ...
            ControlBeta.pethEnvelopeZ;

        PairTable.pairComplete(rowIndex) = true;

        if mod(progressIndex,10) == 0 || ...
                progressIndex == numel(processingRows)
            fprintf('  %d/%d this invocation; total %d/%d complete\n', ...
                progressIndex, ...
                numel(processingRows), ...
                sum(PairTable.pairComplete), ...
                height(PairTable));
        end

        if mod(progressIndex, ...
                checkpointEveryNPairs) == 0 || ...
                progressIndex == numel(processingRows)

            save(checkpointPath, ...
                'PairTable', ...
                'eventPethZ', ...
                'controlPethZ', ...
                '-v7.3');
        end
    end
