pendingRows = find(~PairTable.pairComplete);

if maximumPairsThisInvocation > 0 && ...
        ~isempty(pendingRows)

    nToProcess = min( ...
        numel(pendingRows), ...
        maximumPairsThisInvocation);

    processingRows = ...
        pendingRows(1:nToProcess);

    fprintf('Processing %d pending event-control pairs.\n', ...
        numel(processingRows));

    for progressIndex = 1:numel(processingRows)
        rowIndex = processingRows(progressIndex);

        EventBeta = ...
