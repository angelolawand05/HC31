allAwakePeaksByAnimal = struct();

for animalIndex = 1:numel(fallbackAnimalIDs)
    animalID = string(fallbackAnimalIDs{animalIndex});

    allAwakePeaksByAnimal.( ...
        matlab.lang.makeValidName(char(animalID))) = ...
        double(Master.peakUs( ...
        Master.animal == animalID & ...
        Master.epoch == "RUN1AWAKE"));
end

for animalPosition = 1:numel(animalIndices)
    resSaveIndex = animalIndices(animalPosition);

    if resSaveIndex > numel(resSave)
        continue
    end

    R = resSave(resSaveIndex);
    animalID = string(fallbackAnimalIDs{animalPosition});

    try
        if isfield(R,'spAll') && ...
                ~isempty(R.spAll) && ...
                isfield(R.spAll,'animal')
            animalID = strtrim(string(R.spAll(1).animal));
        elseif isfield(R,'name')
            animalID = strtrim(string(R.name));
        elseif isfield(R,'animal')
            animalID = strtrim(string(R.animal));
        end
    catch
    end

    animalRows = find( ...
        AwakeEvents.animal == animalID);

    if isempty(animalRows)
        continue
    end

    try
        posUnit = R.posMazeLin(1);
        posData = double(posUnit.data);
    catch
        warning('%s has no usable posMazeLin(1).',animalID);
        continue
    end

    if size(posData,2) < 4
        warning('%s position table lacks speed column 4.', ...
            animalID);
        continue
    end

    positionTimeUs = posData(:,1);

    if max(abs(positionTimeUs),[],'omitnan') < 1e6
        positionTimeUs = positionTimeUs*1e6;
    end

    speedCmS = abs(posData(:,4));

    if isfield(posUnit,'unitsPerCm') && ...
            isfield(posUnit,'unitsPerSecond')
        speedCmS = speedCmS .* ...
            (1/posUnit.unitsPerCm) .* ...
            posUnit.unitsPerSecond;
    end

    validPosition = ...
        isfinite(positionTimeUs) & ...
        isfinite(speedCmS);

    positionTimeUs = positionTimeUs(validPosition);
    speedCmS = speedCmS(validPosition);

    [positionTimeUs,uniqueIndex] = ...
        unique(positionTimeUs,'stable');

    speedCmS = speedCmS(uniqueIndex);

    positionTimeSec = positionTimeUs/1e6;
    dtSec = median(diff(positionTimeSec),'omitnan');

    if ~isfinite(dtSec) || dtSec <= 0
        continue
    end

    smoothSamples = max( ...
        1,round(0.25/dtSec));

    speedSmooth = movmean( ...
        speedCmS,smoothSamples,'omitnan');

    acceleration = gradient(speedSmooth) ./ ...
        max(gradient(positionTimeSec),eps);

    acceleration = movmean( ...
        acceleration,smoothSamples,'omitnan');

    halfWindowSamples = max( ...
        1,round(1.0/dtSec));

    maxSpeedTwoSec = movmax( ...
        speedSmooth, ...
        [halfWindowSamples halfWindowSamples]);

    preSampleSpeed = interp1( ...
        positionTimeSec, ...
        speedSmooth, ...
        positionTimeSec-0.6, ...
        'linear',NaN);

    postSampleSpeed = interp1( ...
        positionTimeSec, ...
        speedSmooth, ...
        positionTimeSec+0.6, ...
        'linear',NaN);

    speedChangeTrace = ...
        postSampleSpeed-preSampleSpeed;

    sustainedTrace = ...
        maxSpeedTwoSec <= lowSpeedThresholdCmS & ...
        abs(speedChangeTrace) <= ...
            stableSpeedChangeThresholdCmS & ...
        abs(acceleration) <= ...
            stableAccelerationThresholdCmS2;

    firstAllowedSec = ...
        min(positionTimeSec)+controlMinimumEdgeSec;

    lastAllowedSec = ...
        max(positionTimeSec)-controlMinimumEdgeSec;

    controlGridSec = ...
        (ceil(firstAllowedSec/controlGridStepSec)* ...
        controlGridStepSec): ...
        controlGridStepSec: ...
        lastAllowedSec;

    controlGridUs = controlGridSec(:)*1e6;

    controlGridSpeed = interp1( ...
        positionTimeUs, ...
        speedSmooth, ...
        controlGridUs, ...
        'linear',NaN);

    controlGridAcceleration = interp1( ...
        positionTimeUs, ...
        acceleration, ...
        controlGridUs, ...
        'linear',NaN);

    controlGridSpeedChange = interp1( ...
        positionTimeUs, ...
        speedChangeTrace, ...
        controlGridUs, ...
        'linear',NaN);

    controlGridSustained = interp1( ...
        positionTimeUs, ...
        double(sustainedTrace), ...
        controlGridUs, ...
        'nearest',0) > 0.5;

    allAwakePeaks = ...
        allAwakePeaksByAnimal.( ...
        matlab.lang.makeValidName(char(animalID)));

    controlAllowed = ...
        isfinite(controlGridSpeed) & ...
        isfinite(controlGridAcceleration) & ...
        isfinite(controlGridSpeedChange);

    for controlIndex = 1:numel(controlGridUs)
        if any(abs(allAwakePeaks- ...
                controlGridUs(controlIndex)) <= ...
                controlEventExclusionSec*1e6)
            controlAllowed(controlIndex) = false;
        end
    end

    controlGridUs = controlGridUs(controlAllowed);
    controlGridSpeed = controlGridSpeed(controlAllowed);
    controlGridAcceleration = ...
        controlGridAcceleration(controlAllowed);
    controlGridSpeedChange = ...
        controlGridSpeedChange(controlAllowed);
    controlGridSustained = ...
        controlGridSustained(controlAllowed);

    controlUsed = false(size(controlGridUs));

    for localIndex = 1:numel(animalRows)
        rowIndex = animalRows(localIndex);
        eventUs = double(AwakeEvents.peakUs(rowIndex));

        eventSpeedAtPeak(rowIndex) = interp1( ...
            positionTimeUs,speedSmooth,eventUs, ...
            'linear',NaN);

        eventAccelerationAtPeak(rowIndex) = interp1( ...
            positionTimeUs,acceleration,eventUs, ...
            'linear',NaN);

        eventPreSpeed(rowIndex) = interp1( ...
            positionTimeUs,speedSmooth, ...
            eventUs-0.6e6,'linear',NaN);

        eventPostSpeed(rowIndex) = interp1( ...
            positionTimeUs,speedSmooth, ...
            eventUs+0.6e6,'linear',NaN);

        eventSpeedChange(rowIndex) = ...
            eventPostSpeed(rowIndex)- ...
            eventPreSpeed(rowIndex);

        eventMaxSpeedTwoSec(rowIndex) = interp1( ...
            positionTimeUs,maxSpeedTwoSec,eventUs, ...
            'linear',NaN);

        eventSustainedImmobility(rowIndex) = ...
            eventMaxSpeedTwoSec(rowIndex) <= ...
                lowSpeedThresholdCmS & ...
            abs(eventSpeedChange(rowIndex)) <= ...
                stableSpeedChangeThresholdCmS & ...
            abs(eventAccelerationAtPeak(rowIndex)) <= ...
                stableAccelerationThresholdCmS2;

        eventMovementIncrease(rowIndex) = ...
            eventSpeedChange(rowIndex) > ...
                stableSpeedChangeThresholdCmS | ...
            eventAccelerationAtPeak(rowIndex) > ...
                stableAccelerationThresholdCmS2;

        if isempty(controlGridUs)
            continue
        end

        sameSustained = ...
            controlGridSustained == ...
            eventSustainedImmobility(rowIndex);

        withinTolerance = ...
            abs(controlGridSpeed- ...
                eventSpeedAtPeak(rowIndex)) <= ...
                speedMatchToleranceCmS & ...
            abs(controlGridAcceleration- ...
                eventAccelerationAtPeak(rowIndex)) <= ...
                accelerationMatchToleranceCmS2 & ...
            abs(controlGridSpeedChange- ...
                eventSpeedChange(rowIndex)) <= ...
                speedChangeMatchToleranceCmS & ...
            sameSustained;

        preferred = find(withinTolerance & ~controlUsed);

        if isempty(preferred)
            preferred = find(withinTolerance);
        end

        standardDistance = ...
            ((controlGridSpeed- ...
            eventSpeedAtPeak(rowIndex)) / ...
            max(speedMatchToleranceCmS,eps)).^2 + ...
            ((controlGridAcceleration- ...
            eventAccelerationAtPeak(rowIndex)) / ...
            max(accelerationMatchToleranceCmS2,eps)).^2 + ...
            ((controlGridSpeedChange- ...
            eventSpeedChange(rowIndex)) / ...
            max(speedChangeMatchToleranceCmS,eps)).^2 + ...
            4*double(~sameSustained);

        if isempty(preferred)
            [minimumDistance,selectedControl] = ...
                min(standardDistance);
        else
            [minimumDistance,relativeControl] = ...
                min(standardDistance(preferred));

            selectedControl = ...
                preferred(relativeControl);
        end

        controlUs(rowIndex) = ...
            controlGridUs(selectedControl);

        controlSpeedAtPeak(rowIndex) = ...
            controlGridSpeed(selectedControl);

        controlAccelerationAtPeak(rowIndex) = ...
            controlGridAcceleration(selectedControl);

        controlSpeedChange(rowIndex) = ...
            controlGridSpeedChange(selectedControl);

        controlSustainedImmobility(rowIndex) = ...
            controlGridSustained(selectedControl);

        controlMatchDistance(rowIndex) = ...
            minimumDistance;

        controlUsed(selectedControl) = true;
    end
end

