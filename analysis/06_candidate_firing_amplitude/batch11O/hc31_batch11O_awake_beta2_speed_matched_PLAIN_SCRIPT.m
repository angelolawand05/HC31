writetable(Progress,fullfile(outputFolder, ...
    'hc31_batch11O_awake_beta2_PROGRESS.csv'));

if any(~PairTable.pairComplete)
    fprintf('\nStage B checkpoint saved. Rerun and choose Full/resume.\n');
else
    PairTable.eventMinusControlPostMinusPreZ = ...
        PairTable.eventPostMinusPreZ- ...
        PairTable.controlPostMinusPreZ;

    PairTable.eventMinusControlCentralMinusPreZ = ...
        PairTable.eventCentralMinusPreZ- ...
        PairTable.controlCentralMinusPreZ;

    PairTable.eventMinusControlPostBurstCountChange = ...
        (PairTable.eventPostBurstCount- ...
        PairTable.eventPreBurstCount) - ...
        (PairTable.controlPostBurstCount- ...
        PairTable.controlPreBurstCount);

    PairTable.eventMinusControlPostBurstFractionChange = ...
        (PairTable.eventPostBurstFraction- ...
        PairTable.eventPreBurstFraction) - ...
        (PairTable.controlPostBurstFraction- ...
        PairTable.controlPreBurstFraction);

    writetable(PairTable,fullfile(outputFolder, ...
        'hc31_batch11O_awake_beta2_event_control_pairs.csv'));

    %% Animal summaries

    setNames = ["TierA","TierAB","TierAC","TierABC"];
    movementGroups = [ ...
        "AllMatched", ...
        "SustainedImmobility", ...
        "StableLowSpeed", ...
        "MovementIncrease"];

    animals = unique(PairTable.animal,'stable');
    summaryRows = {};

    for setIndex = 1:numel(setNames)
        setName = setNames(setIndex);

        if setName == "TierA"
            setMask = PairTable.inSetTierA;
        elseif setName == "TierAB"
            setMask = PairTable.inSetTierAB;
        elseif setName == "TierAC"
            setMask = PairTable.inSetTierAC;
        else
            setMask = PairTable.inSetTierABC;
        end

        for movementIndex = 1:numel(movementGroups)
            movementName = ...
                movementGroups(movementIndex);

            if movementName == "AllMatched"
                movementMask = ...
                    isfinite(PairTable.controlUs);
            elseif movementName == "SustainedImmobility"
                movementMask = ...
                    PairTable.sustainedImmobility & ...
                    PairTable.controlSustainedImmobility;
            elseif movementName == "StableLowSpeed"
                movementMask = ...
                    PairTable.eventSpeedAtPeakCmS <= ...
                        lowSpeedThresholdCmS & ...
                    abs(PairTable.eventSpeedChangeCmS) <= ...
                        stableSpeedChangeThresholdCmS & ...
                    abs(PairTable.controlSpeedChangeCmS) <= ...
                        stableSpeedChangeThresholdCmS;
            else
                movementMask = ...
                    PairTable.movementIncrease;
            end

            for animalIndex = 1:numel(animals)
                animalID = animals(animalIndex);

                mask = ...
                    setMask & ...
                    movementMask & ...
                    PairTable.animal == animalID & ...
                    PairTable.pairComplete & ...
                    strlength( ...
                    PairTable.eventBeta2FailureReason) == 0 & ...
                    strlength( ...
                    PairTable.controlBeta2FailureReason) == 0;

                nPairs = sum(mask);

                if nPairs == 0
                    continue
                end

                summaryRows(end+1,:) = { ...
                    char(setName), ...
                    char(movementName), ...
                    char(animalID), ...
                    nPairs, ...
                    mean(PairTable.eventPreMeanZ(mask), ...
                        'omitnan'), ...
                    mean(PairTable.eventEarlyPostMeanZ(mask), ...
                        'omitnan'), ...
                    mean(PairTable.eventPostMinusPreZ(mask), ...
                        'omitnan'), ...
                    mean(PairTable.controlPostMinusPreZ(mask), ...
                        'omitnan'), ...
                    mean(PairTable. ...
                        eventMinusControlPostMinusPreZ(mask), ...
                        'omitnan'), ...
                    mean(PairTable. ...
                        eventMinusControlCentralMinusPreZ(mask), ...
                        'omitnan'), ...
                    mean(PairTable. ...
                        eventMinusControlPostBurstCountChange(mask), ...
                        'omitnan'), ...
                    mean(PairTable. ...
                        eventMinusControlPostBurstFractionChange(mask), ...
                        'omitnan'), ...
                    mean(PairTable.eventSpeedAtPeakCmS(mask), ...
                        'omitnan'), ...
                    mean(PairTable.eventAccelerationAtPeakCmS2(mask), ...
                        'omitnan'), ...
                    mean(PairTable.eventSpeedChangeCmS(mask), ...
                        'omitnan'), ...
                    mean(PairTable.controlMatchDistance(mask), ...
                        'omitnan')}; %#ok<SAGROW>
            end
        end
    end

    AnimalSummary = cell2table(summaryRows, ...
        'VariableNames', { ...
        'eventSet', ...
        'movementGroup', ...
        'animal', ...
        'nPairs', ...
        'eventPreMeanZ', ...
        'eventEarlyPostMeanZ', ...
        'eventPostMinusPreZ', ...
        'controlPostMinusPreZ', ...
        'eventMinusControlPostMinusPreZ', ...
        'eventMinusControlCentralMinusPreZ', ...
        'eventMinusControlPostBurstCountChange', ...
        'eventMinusControlPostBurstFractionChange', ...
        'meanEventSpeedCmS', ...
        'meanEventAccelerationCmS2', ...
        'meanEventSpeedChangeCmS', ...
        'meanControlMatchDistance'});

    writetable(AnimalSummary,fullfile(outputFolder, ...
        'hc31_batch11O_awake_beta2_animal_summary.csv'));

    %% PETH summary

    pethRows = {};

    for setIndex = 1:numel(setNames)
        setName = setNames(setIndex);

        if setName == "TierA"
            setMask = PairTable.inSetTierA;
        elseif setName == "TierAB"
            setMask = PairTable.inSetTierAB;
        elseif setName == "TierAC"
            setMask = PairTable.inSetTierAC;
        else
            setMask = PairTable.inSetTierABC;
        end

        for movementIndex = 1:numel(movementGroups)
            movementName = ...
                movementGroups(movementIndex);

            if movementName == "AllMatched"
                movementMask = ...
                    isfinite(PairTable.controlUs);
            elseif movementName == "SustainedImmobility"
                movementMask = ...
                    PairTable.sustainedImmobility & ...
                    PairTable.controlSustainedImmobility;
            elseif movementName == "StableLowSpeed"
                movementMask = ...
                    PairTable.eventSpeedAtPeakCmS <= ...
                        lowSpeedThresholdCmS & ...
                    abs(PairTable.eventSpeedChangeCmS) <= ...
                        stableSpeedChangeThresholdCmS & ...
                    abs(PairTable.controlSpeedChangeCmS) <= ...
                        stableSpeedChangeThresholdCmS;
            else
                movementMask = ...
                    PairTable.movementIncrease;
            end

            animalEventPeth = [];
            animalControlPeth = [];
            nPairsByAnimal = [];

            for animalIndex = 1:numel(animals)
                animalID = animals(animalIndex);

                mask = ...
                    setMask & movementMask & ...
                    PairTable.animal == animalID & ...
                    PairTable.pairComplete & ...
                    strlength( ...
                    PairTable.eventBeta2FailureReason) == 0 & ...
                    strlength( ...
                    PairTable.controlBeta2FailureReason) == 0;

                rows = find(mask);

                if isempty(rows)
                    continue
                end

                animalEventPeth(end+1,:) = ...
                    mean(eventPethZ(rows,:),1,'omitnan'); %#ok<SAGROW>

                animalControlPeth(end+1,:) = ...
                    mean(controlPethZ(rows,:),1,'omitnan'); %#ok<SAGROW>

                nPairsByAnimal(end+1,1) = ...
                    numel(rows); %#ok<SAGROW>
            end

            if isempty(animalEventPeth)
                continue
            end

            eventMean = mean( ...
                animalEventPeth,1,'omitnan');

            eventSem = std( ...
                animalEventPeth,0,1,'omitnan') / ...
                sqrt(size(animalEventPeth,1));

            controlMean = mean( ...
                animalControlPeth,1,'omitnan');

            controlSem = std( ...
                animalControlPeth,0,1,'omitnan') / ...
                sqrt(size(animalControlPeth,1));

            for binIndex = 1:nBins
                pethRows(end+1,:) = { ...
                    char(setName), ...
                    char(movementName), ...
                    settings.beta2PethCenters(binIndex), ...
                    eventMean(binIndex), ...
                    eventSem(binIndex), ...
                    controlMean(binIndex), ...
                    controlSem(binIndex), ...
                    size(animalEventPeth,1), ...
                    sum(nPairsByAnimal)}; %#ok<SAGROW>
            end
        end
    end

    PethSummary = cell2table(pethRows, ...
        'VariableNames', { ...
        'eventSet', ...
        'movementGroup', ...
        'timeFromEventSec', ...
        'meanEventBeta2EnvelopeZ', ...
        'semEventBeta2EnvelopeZ', ...
        'meanControlBeta2EnvelopeZ', ...
        'semControlBeta2EnvelopeZ', ...
        'nAnimals', ...
        'nPairs'});

    writetable(PethSummary,fullfile(outputFolder, ...
        'hc31_batch11O_awake_beta2_animal_weighted_PETH.csv'));

    %% Statistics

    statRows = {};
    metricNames = { ...
        'eventPostMinusPreZ', ...
        'eventMinusControlPostMinusPreZ', ...
        'eventMinusControlCentralMinusPreZ', ...
        'eventMinusControlPostBurstCountChange', ...
        'eventMinusControlPostBurstFractionChange'};

    for setIndex = 1:numel(setNames)
        setName = setNames(setIndex);

        for movementIndex = 1:numel(movementGroups)
            movementName = ...
                movementGroups(movementIndex);

            mask = ...
                string(AnimalSummary.eventSet) == setName & ...
                string(AnimalSummary.movementGroup) == ...
                    movementName;

            for metricIndex = 1:numel(metricNames)
                metricName = metricNames{metricIndex};
                values = double( ...
                    AnimalSummary.(metricName)(mask));

                values = values(isfinite(values));
                pValue = NaN;
                signedRank = NaN;

                if numel(values) >= 3
                    try
                        [pValue,~,stats] = ...
                            signrank(values,0);

                        signedRank = stats.signedrank;
                    catch
                    end
                end

                statRows(end+1,:) = { ...
                    char(setName), ...
                    char(movementName), ...
                    metricName, ...
                    numel(values), ...
                    mean(values,'omitnan'), ...
                    median(values,'omitnan'), ...
                    pValue, ...
                    signedRank}; %#ok<SAGROW>
            end
        end
    end

    Beta2Stats = cell2table(statRows, ...
        'VariableNames', { ...
        'eventSet', ...
        'movementGroup', ...
        'metric', ...
        'nAnimals', ...
        'meanEffect', ...
        'medianEffect', ...
        'pValue', ...
        'signedRank'});

    Beta2Stats.qValueBH = ...
        hc31_batch11O_bh_fdr(Beta2Stats.pValue);

    writetable(Beta2Stats,fullfile(outputFolder, ...
        'hc31_batch11O_awake_beta2_statistics.csv'));

    %% Figures

    plotMask = ...
        string(PethSummary.eventSet) == "TierAC" & ...
        string(PethSummary.movementGroup) == ...
            "SustainedImmobility";

    fig = figure( ...
        'Visible','off', ...
        'Color','w', ...
        'Position',[80 80 1200 720]);

    hold on

    plot( ...
        PethSummary.timeFromEventSec(plotMask), ...
        PethSummary.meanEventBeta2EnvelopeZ(plotMask), ...
        'LineWidth',1.8);

    plot( ...
        PethSummary.timeFromEventSec(plotMask), ...
        PethSummary.meanControlBeta2EnvelopeZ(plotMask), ...
        'LineWidth',1.8);

    xline(0,'k--');
    yline(0,':');
    xlabel('Time from event or matched pseudo-time (s)');
    ylabel('Local beta2 envelope robust z');
    title('Tier A+C sustained immobility: event vs movement-matched control');
    legend({'Event','Matched control'},'Location','best');
    grid on
    box off

    exportgraphics(fig,fullfile(figureFolder, ...
        'batch11O_TierAC_sustained_immobility_beta2_PETH.png'), ...
        'Resolution',200);

    close(fig);

    fig = figure( ...
        'Visible','off', ...
        'Color','w', ...
        'Position',[80 80 1100 700]);

    summaryMask = ...
        string(AnimalSummary.eventSet) == "TierAC" & ...
        ismember( ...
        string(AnimalSummary.movementGroup), ...
        ["SustainedImmobility","MovementIncrease"]);

    categories = categorical( ...
        string(AnimalSummary.movementGroup(summaryMask)));

    scatter(categories, ...
        AnimalSummary. ...
        eventMinusControlPostMinusPreZ(summaryMask), ...
        55,'filled');

    yline(0,'k--');
    ylabel('Event-control beta2 post-minus-pre z');
    title('Movement-stratified beta2 coupling by animal');
    grid on
    box off

    exportgraphics(fig,fullfile(figureFolder, ...
        'batch11O_movement_stratified_beta2_effect.png'), ...
        'Resolution',200);

    close(fig);

    %% Text summary

    fid = fopen(fullfile(outputFolder, ...
        'hc31_batch11O_STAGE_B_SUMMARY.txt'),'w');

    if fid >= 0
        fprintf(fid, ...
            'HC-31 Batch 11O Stage B\n');
        fprintf(fid, ...
            'Run1-awake beta2 coupling with matched controls\n');
        fprintf(fid, ...
            '================================================\n\n');

        fprintf(fid,'Corrected master table:\n%s\n\n',masterPath);
        fprintf(fid,'Event-control pairs: %d\n',height(PairTable));
        fprintf(fid,'Beta2 band: 23-30 Hz\n');
        fprintf(fid,'Burst threshold: robust z >= %.1f\n', ...
            settings.beta2BurstThresholdZ);
        fprintf(fid,'Minimum burst duration: %.0f ms\n\n', ...
            settings.beta2BurstMinDurationSec*1000);

        fprintf(fid,'Primary analysis\n');
        fprintf(fid,'----------------\n');
        fprintf(fid,[ ...
            'Tier A+C events during sustained immobility, ', ...
            'compared with same-animal pseudo-times matched ', ...
            'on speed, acceleration and speed change.\n\n']);

        fprintf(fid,'Interpretation boundaries\n');
        fprintf(fid,'-------------------------\n');
        fprintf(fid,[ ...
            'Local beta2 z is normalised independently in each ', ...
            'event/control segment.\n']);
        fprintf(fid,[ ...
            'Matched controls reduce movement confounding but ', ...
            'do not establish causality.\n']);
        fprintf(fid,[ ...
            'Animal-level tests use at most five subjects and ', ...
            'should be reported with effect sizes and raw points.\n']);

        fclose(fid);
    end

    fprintf('\nBatch 11O Stage B complete.\n');
    fprintf('Output folder:\n  %s\n',outputFolder);
end
