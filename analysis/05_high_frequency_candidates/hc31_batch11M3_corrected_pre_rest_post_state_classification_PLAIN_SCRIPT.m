    deltaLogValues = ...
        StateWindows.deltaLogPower(animalRows);

    highLogValues = ...
        StateWindows.highFrequencyLogPower(animalRows);

    rawLogValues = ...
        StateWindows.rawLogRms(animalRows);

    thetaDeltaMedian = median( ...
        thetaDeltaValues, 'omitnan');

    thetaDeltaMad = 1.4826 * median( ...
        abs(thetaDeltaValues - thetaDeltaMedian), ...
        'omitnan');

    thetaMedian = median(thetaLogValues, 'omitnan');
    thetaMad = 1.4826 * median( ...
        abs(thetaLogValues - thetaMedian), ...
        'omitnan');

    deltaMedian = median(deltaLogValues, 'omitnan');
    deltaMad = 1.4826 * median( ...
        abs(deltaLogValues - deltaMedian), ...
        'omitnan');

    highMedian = median(highLogValues, 'omitnan');
    highMad = 1.4826 * median( ...
        abs(highLogValues - highMedian), ...
        'omitnan');

    rawMedian = median(rawLogValues, 'omitnan');
    rawMad = 1.4826 * median( ...
        abs(rawLogValues - rawMedian), ...
        'omitnan');

    if ~isfinite(thetaDeltaMad) || thetaDeltaMad <= 0
        thetaDeltaMad = std(thetaDeltaValues, 'omitnan');
    end

    if ~isfinite(thetaMad) || thetaMad <= 0
        thetaMad = std(thetaLogValues, 'omitnan');
    end

    if ~isfinite(deltaMad) || deltaMad <= 0
        deltaMad = std(deltaLogValues, 'omitnan');
    end

    if ~isfinite(highMad) || highMad <= 0
        highMad = std(highLogValues, 'omitnan');
    end

    if ~isfinite(rawMad) || rawMad <= 0
        rawMad = std(rawLogValues, 'omitnan');
    end

    thetaDeltaMad = max(thetaDeltaMad, eps);
    thetaMad = max(thetaMad, eps);
    deltaMad = max(deltaMad, eps);
    highMad = max(highMad, eps);
    rawMad = max(rawMad, eps);

    StateWindows.thetaDeltaRobustZ(animalRows) = ...
        (thetaDeltaValues - thetaDeltaMedian) ./ ...
        thetaDeltaMad;

    StateWindows.thetaPowerRobustZ(animalRows) = ...
        (thetaLogValues - thetaMedian) ./ thetaMad;

    StateWindows.deltaPowerRobustZ(animalRows) = ...
        (deltaLogValues - deltaMedian) ./ deltaMad;

    StateWindows.highFrequencyRobustZ(animalRows) = ...
        (highLogValues - highMedian) ./ highMad;

    StateWindows.rawRmsRobustZ(animalRows) = ...
        (rawLogValues - rawMedian) ./ rawMad;

    thresholdRows(end+1,:) = { ...
        char(animalID), ...
        numel(animalRows), ...
        thetaDeltaMedian, ...
        thetaDeltaMad, ...
        thetaMedian, ...
        thetaMad, ...
        deltaMedian, ...
        deltaMad, ...
        highMedian, ...
        highMad, ...
        rawMedian, ...
        rawMad}; %#ok<SAGROW>
end

