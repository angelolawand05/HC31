                trainMergedRetained == 0);

            if isempty(candidates)
                candidates = find(trainTP > 0);
            end

            score = [ ...
                -trainPpvScore(candidates), ...
                -trainBalancedAccuracy(candidates), ...
                trainMergedRetained(candidates), ...
                -trainSensitivity(candidates), ...
                -trainTP(candidates)];

        elseif thisProfile == "Balanced"
            candidates = find(trainTP >= 5);

            score = [ ...
                -trainBalancedAccuracy(candidates), ...
                trainMergedRetained(candidates), ...
                -trainPpvScore(candidates), ...
                -trainSensitivity(candidates)];

        else
            candidates = find( ...
                trainTP >= 5 & ...
                trainSpecificity >= 0.50);

            score = [ ...
                -trainSensitivity(candidates), ...
                trainMergedRetained(candidates), ...
                -trainPpvScore(candidates), ...
                -trainBalancedAccuracy(candidates)];
        end

        [~, scoreOrder] = sortrows(score);
        selectedIndex = ...
            candidates(scoreOrder(1));

        testMask = testPositive | testNegative;
        testTruth = isPositive(testMask);
        testPrediction = ...
            predictedPass(testMask,selectedIndex);

        TP = sum(testPrediction & testTruth);
        FP = sum(testPrediction & ~testTruth);
        FN = sum(~testPrediction & testTruth);
        TN = sum(~testPrediction & ~testTruth);

        thisSensitivity = ...
            TP / max(TP+FN,1);

        thisSpecificity = ...
            TN / max(TN+FP,1);

        if TP + FP > 0
            thisPPV = TP / (TP+FP);
        else
            thisPPV = NaN;
        end

        thisBalancedAccuracy = ...
            0.5 * ( ...
            thisSensitivity + ...
            thisSpecificity);

        cvAnimal(end+1,1) = ...
            heldOutAnimal; %#ok<SAGROW>
        cvProfile(end+1,1) = ...
            thisProfile; %#ok<SAGROW>
        cvSelectedRuleIndex(end+1,1) = ...
            selectedIndex; %#ok<SAGROW>

        cvTP(end+1,1) = TP; %#ok<SAGROW>
        cvFP(end+1,1) = FP; %#ok<SAGROW>
        cvFN(end+1,1) = FN; %#ok<SAGROW>
        cvTN(end+1,1) = TN; %#ok<SAGROW>

        cvSensitivity(end+1,1) = ...
            thisSensitivity; %#ok<SAGROW>
        cvSpecificity(end+1,1) = ...
            thisSpecificity; %#ok<SAGROW>
        cvPPV(end+1,1) = ...
            thisPPV; %#ok<SAGROW>
        cvBalancedAccuracy(end+1,1) = ...
            thisBalancedAccuracy; %#ok<SAGROW>

        cvMergedRetained(end+1,1) = ...
            sum( ...
            predictedPass(:,selectedIndex) & ...
            isMergedLabel & ...
            T.animal == heldOutAnimal); %#ok<SAGROW>
    end
end

