%% Per-event refined feature extraction

for rr = 1:nEvents
    blindID = char(T.blindID(rr));
    peakUs = double(T.peakUs(rr));
    detectorStartUs = double(T.startUs(rr));
    detectorEndUs = double(T.endUs(rr));
    cscFile = char(T.cscFile(rr));

    fprintf('[%d/%d] %s\n', rr, nEvents, blindID);

    if exist(cscFile, 'file') ~= 2
        refinedFailureReason(rr) = ...
            "CSC file does not exist: " + string(cscFile);

        failureBlindID(end+1,1) = string(blindID); %#ok<SAGROW>
        failureReason(end+1,1) = ...
            refinedFailureReason(rr); %#ok<SAGROW>
        continue
    end

    loadStartUs = peakUs - ...
        loadHalfWindowSec * 1e6;

    loadEndUs = peakUs + ...
        loadHalfWindowSec * 1e6;

    try
        [tRec, vRec, header] = Nlx2MatCSC( ...
            cscFile, ...
            [1 0 0 0 1], ...
            1, ...
            4, ...
            [loadStartUs loadEndUs]);
    catch ME
        refinedFailureReason(rr) = ...
            "Nlx2MatCSC read failed: " + string(ME.message);

        failureBlindID(end+1,1) = string(blindID); %#ok<SAGROW>
        failureReason(end+1,1) = ...
            refinedFailureReason(rr); %#ok<SAGROW>
        continue
    end

    if isempty(tRec) || isempty(vRec)
        refinedFailureReason(rr) = ...
            "CSC interval read returned no data.";

        failureBlindID(end+1,1) = string(blindID); %#ok<SAGROW>
        failureReason(end+1,1) = ...
            refinedFailureReason(rr); %#ok<SAGROW>
        continue
    end

    tRec = double(tRec(:));
    vRec = double(vRec);
    vRawVector = double(vRec(:));

    headerInfo = struct();

    try
        headerInfo = readNlxHeader(header);
    catch
    end

    tDiff = diff(tRec);
    tDiffGood = tDiff(isfinite(tDiff) & tDiff > 0);

    if isempty(tDiffGood)
        refinedFailureReason(rr) = ...
            "Could not estimate CSC sampling rate.";

        failureBlindID(end+1,1) = string(blindID); %#ok<SAGROW>
        failureReason(end+1,1) = ...
            refinedFailureReason(rr); %#ok<SAGROW>
        continue
    end

    modeDifferenceUs = mode(round(tDiffGood));
    noSkip = abs(tDiff - modeDifferenceUs) <= 2;

    if any(noSkip)
        FsRaw = 1 / ...
            (mean(tDiff(noSkip)) / 512 / 1e6);
    else
        FsRaw = 1 / ...
            (median(tDiffGood) / 512 / 1e6);
    end

    if all(noSkip)
        timeAllUs = linspace( ...
            tRec(1), ...
            tRec(end) + ...
                (511 / FsRaw) * 1e6, ...
            numel(vRawVector))';

        lfpVector = vRawVector;
    else
        timeGridUs = ( ...
            tRec(1): ...
            (1 / FsRaw) * 1e6: ...
            (tRec(end) + ...
            (511 / FsRaw) * 1e6))';

        valueGrid = nan(numel(timeGridUs),1);
        insertionPosition = 1;

        for rec = 1:size(vRec,2)
            while insertionPosition <= ...
                    numel(timeGridUs) && ...
                    abs(tRec(rec) - ...
                    timeGridUs(insertionPosition)) >= 2
                insertionPosition = ...
                    insertionPosition + 1;
            end

            if insertionPosition + 511 <= ...
                    numel(valueGrid)
                valueGrid( ...
                    insertionPosition: ...
                    insertionPosition+511) = ...
                    vRec(:,rec);
            end

            insertionPosition = ...
                insertionPosition + 512;
        end

        timeAllUs = timeGridUs;
        lfpVector = valueGrid;
    end

    rawScale = 1;

    if isfield(headerInfo, 'ADBitVolts')
        rawScale = ...
            double(headerInfo.ADBitVolts(1)) * 1e6;
    end

    lfpRaw = lfpVector .* rawScale;
    validRaw = isfinite(lfpRaw);

    if ~any(validRaw)
        refinedFailureReason(rr) = ...
            "Every LFP sample was invalid.";

        failureBlindID(end+1,1) = string(blindID); %#ok<SAGROW>
        failureReason(end+1,1) = ...
            refinedFailureReason(rr); %#ok<SAGROW>
        continue
    end

    fillValue = median(lfpRaw(validRaw), 'omitnan');
    lfpFilled = lfpRaw;
    lfpFilled(~validRaw) = fillValue;

    downsampleFactor = ...
        max(1, round(FsRaw / targetFs));

    FsDs = FsRaw / downsampleFactor;

    if downsampleFactor > 1
        try
            lfpDs = decimate( ...
                lfpFilled, downsampleFactor);
        catch
            lfpDs = ...
                lfpFilled(1:downsampleFactor:end);
        end

        timeDsUs = ...
            timeAllUs(1:downsampleFactor:end);

        validDs = ...
            validRaw(1:downsampleFactor:end);
    else
        lfpDs = lfpFilled;
        timeDsUs = timeAllUs;
        validDs = validRaw;
    end

    nCommon = min([ ...
        numel(lfpDs), ...
        numel(timeDsUs), ...
        numel(validDs)]);

    lfpDs = double(lfpDs(1:nCommon));
    timeDsUs = double(timeDsUs(1:nCommon));
    validDs = logical(validDs(1:nCommon));

    if upperHighBandHz(2) >= FsDs / 2
        upperHighBandEffectiveHz = ...
            [upperHighBandHz(1), ...
            floor(FsDs / 2 - 2)];
    else
        upperHighBandEffectiveHz = ...
            upperHighBandHz;
    end

    if rippleBandHz(2) >= FsDs / 2 || ...
            upperHighBandEffectiveHz(2) <= ...
            upperHighBandEffectiveHz(1)
        refinedFailureReason(rr) = ...
            "Downsampled Nyquist frequency was too low.";

        failureBlindID(end+1,1) = string(blindID); %#ok<SAGROW>
        failureReason(end+1,1) = ...
            refinedFailureReason(rr); %#ok<SAGROW>
        continue
    end

    try
        [bRipple, aRipple] = butter( ...
            filterOrder, ...
            rippleBandHz / (FsDs/2), ...
            'bandpass');

        [bWideHigh, aWideHigh] = butter( ...
            filterOrder, ...
            wideHighBandHz / (FsDs/2), ...
            'bandpass');

        [bSharp, aSharp] = butter( ...
            filterOrder, ...
            sharpWaveBandHz / (FsDs/2), ...
            'bandpass');

        rippleFiltered = ...
            filtfilt(bRipple, aRipple, lfpDs);

        wideHighFiltered = ...
            filtfilt(bWideHigh, aWideHigh, lfpDs);

        sharpFiltered = ...
            filtfilt(bSharp, aSharp, lfpDs);
    catch ME
        refinedFailureReason(rr) = ...
            "Filtering failed: " + string(ME.message);

        failureBlindID(end+1,1) = string(blindID); %#ok<SAGROW>
        failureReason(end+1,1) = ...
            refinedFailureReason(rr); %#ok<SAGROW>
        continue
    end

    relativeTimeSec = ...
        (timeDsUs - peakUs) / 1e6;

    rippleEnvelope = ...
        abs(hilbert(rippleFiltered));

    envelopeSmoothingSamples = ...
        max(1, round(envelopeSmoothingSec * FsDs));

    rippleEnvelope = movmean( ...
        rippleEnvelope, ...
        envelopeSmoothingSamples, ...
        'omitnan');

    baselineMask = ...
        validDs & ...
        isfinite(rippleEnvelope) & ...
        abs(relativeTimeSec) >= ...
            baselineExclusionHalfWindowSec;

    if sum(baselineMask) < ...
            round(minimumBaselineDurationSec * FsDs)
        baselineMask = ...
            validDs & ...
            isfinite(rippleEnvelope);
    end

    baselineEnvelope = ...
        rippleEnvelope(baselineMask);

    baselineMedian = ...
        median(baselineEnvelope, 'omitnan');

    baselineMad = ...
        median(abs( ...
            baselineEnvelope - baselineMedian), ...
            'omitnan');

    baselineSigma = 1.4826 * baselineMad;

    if ~isfinite(baselineSigma) || ...
            baselineSigma <= 0
        baselineSigma = ...
            std(baselineEnvelope, 'omitnan');
    end

    if ~isfinite(baselineSigma) || ...
            baselineSigma <= 0
        baselineSigma = 1;
    end

    envelopeZ = ...
        (rippleEnvelope - baselineMedian) ./ ...
        baselineSigma;

    detectorStartTimeSec = ...
        (detectorStartUs - peakUs) / 1e6;

    detectorEndTimeSec = ...
        (detectorEndUs - peakUs) / 1e6;

    parentSearchStartSec = max( ...
        -parentPeakMaximumHalfWindowSec, ...
        detectorStartTimeSec - parentPeakPaddingSec);

    parentSearchEndSec = min( ...
        parentPeakMaximumHalfWindowSec, ...
        detectorEndTimeSec + parentPeakPaddingSec);

    if ~isfinite(parentSearchStartSec) || ...
            ~isfinite(parentSearchEndSec) || ...
            parentSearchEndSec - parentSearchStartSec < 0.020

        fallbackHalfWidthSec = max( ...
            0.030, ...
            min(parentPeakMaximumHalfWindowSec, ...
            0.5 * max(detectorEndTimeSec - detectorStartTimeSec, 0.040) + ...
            parentPeakPaddingSec));

        parentSearchStartSec = -fallbackHalfWidthSec;
        parentSearchEndSec = fallbackHalfWidthSec;
    end

    analysisMask = ...
        relativeTimeSec >= parentSearchStartSec & ...
        relativeTimeSec <= parentSearchEndSec & ...
        isfinite(envelopeZ);

    analysisRows = find(analysisMask);

    if numel(analysisRows) < ...
            round(0.020 * FsDs)
        refinedFailureReason(rr) = ...
            "Insufficient samples in analysis window.";

        failureBlindID(end+1,1) = string(blindID); %#ok<SAGROW>
        failureReason(end+1,1) = ...
            refinedFailureReason(rr); %#ok<SAGROW>
        continue
    end

    analysisEnvelopeZ = envelopeZ(analysisRows);
    analysisTimeSec = relativeTimeSec(analysisRows);

    minimumPeakDistanceSamples = ...
        max(1, round( ...
        peakMinimumDistanceSec * FsDs));

    % Compatibility-safe peak detector.
    %
    % The first Batch 11L2 run used the MinPeakProminence option of
    % findpeaks. On this MATLAB installation that call failed silently
    % inside the compatibility catch block, forcing every event to a
    % single fallback maximum. The manual implementation below avoids
    % version-specific findpeaks options and calculates local prominence
    % and half-prominence width explicitly.
    prominenceSearchHalfWindowSamples = ...
        max(3, round(0.080 * FsDs));

    xPeak = analysisEnvelopeZ(:);
    nPeakSamples = numel(xPeak);

    candidatePeakLocations = find( ...
        xPeak(2:end-1) >= xPeak(1:end-2) & ...
        xPeak(2:end-1) > xPeak(3:end)) + 1;

    if nPeakSamples >= 2
        if xPeak(1) > xPeak(2)
            candidatePeakLocations = [ ...
                1; candidatePeakLocations(:)];
        end

        if xPeak(end) >= xPeak(end-1)
            candidatePeakLocations = [ ...
                candidatePeakLocations(:); ...
                nPeakSamples];
        end
    end

    candidatePeakLocations = ...
        candidatePeakLocations( ...
        xPeak(candidatePeakLocations) >= ...
        peakHeightZ);

    candidatePeakValues = ...
        xPeak(candidatePeakLocations);

    candidatePeakProminences = ...
        nan(size(candidatePeakValues));

    candidatePeakWidths = ...
        nan(size(candidatePeakValues));

    for peakCandidateIndex = ...
            1:numel(candidatePeakLocations)

        thisLocation = ...
            candidatePeakLocations( ...
            peakCandidateIndex);

        thisPeakValue = ...
            candidatePeakValues( ...
            peakCandidateIndex);

        leftSearchStart = max( ...
            1, ...
            thisLocation - ...
            prominenceSearchHalfWindowSamples);

        rightSearchEnd = min( ...
            nPeakSamples, ...
            thisLocation + ...
            prominenceSearchHalfWindowSamples);

        leftMinimum = min( ...
            xPeak(leftSearchStart:thisLocation), ...
            [], ...
            'omitnan');

        rightMinimum = min( ...
            xPeak(thisLocation:rightSearchEnd), ...
            [], ...
            'omitnan');

        localContour = max( ...
            leftMinimum, ...
            rightMinimum);

        thisProminence = ...
            thisPeakValue - localContour;

        candidatePeakProminences( ...
            peakCandidateIndex) = ...
            thisProminence;

        widthLevel = ...
            thisPeakValue - ...
            0.5 * max(thisProminence, 0);

        leftWidthIndex = thisLocation;

        while leftWidthIndex > 1 && ...
                xPeak(leftWidthIndex) > ...
                widthLevel
            leftWidthIndex = ...
                leftWidthIndex - 1;
        end

        rightWidthIndex = thisLocation;

        while rightWidthIndex < ...
                nPeakSamples && ...
                xPeak(rightWidthIndex) > ...
                widthLevel
            rightWidthIndex = ...
                rightWidthIndex + 1;
        end

        candidatePeakWidths( ...
            peakCandidateIndex) = ...
            rightWidthIndex - ...
            leftWidthIndex;
    end

    prominenceKeep = ...
        candidatePeakProminences >= ...
        peakProminenceZ;

    candidatePeakLocations = ...
        candidatePeakLocations(prominenceKeep);

    candidatePeakValues = ...
        candidatePeakValues(prominenceKeep);

    candidatePeakProminences = ...
        candidatePeakProminences(prominenceKeep);

    candidatePeakWidths = ...
        candidatePeakWidths(prominenceKeep);

    % Non-maximum suppression enforces minimum temporal separation while
    % retaining the largest peaks first.
    selectedCandidateIndices = [];

    if ~isempty(candidatePeakValues)
        [~, candidateAmplitudeOrder] = ...
            sort(candidatePeakValues, 'descend');

        for candidateOrderIndex = ...
                1:numel(candidateAmplitudeOrder)

            candidateIndex = ...
                candidateAmplitudeOrder( ...
                candidateOrderIndex);

            candidateLocation = ...
                candidatePeakLocations( ...
                candidateIndex);

            if isempty(selectedCandidateIndices)
                selectedCandidateIndices = ...
                    candidateIndex;
            else
                selectedLocations = ...
                    candidatePeakLocations( ...
                    selectedCandidateIndices);

                if all(abs( ...
                        selectedLocations - ...
                        candidateLocation) >= ...
                        minimumPeakDistanceSamples)

                    selectedCandidateIndices( ...
                        end+1,1) = ...
                        candidateIndex; %#ok<SAGROW>
                end
            end
        end
    end

    allPeakLocations = ...
        candidatePeakLocations( ...
        selectedCandidateIndices);

    allPeakValues = ...
        candidatePeakValues( ...
        selectedCandidateIndices);

    allPeakWidths = ...
        candidatePeakWidths( ...
        selectedCandidateIndices);

    allPeakProminences = ...
        candidatePeakProminences( ...
        selectedCandidateIndices);

    if isempty(allPeakValues)
        [maximumEnvelopeZ, maximumLocation] = ...
            max(analysisEnvelopeZ);

        allPeakValues = maximumEnvelopeZ;
        allPeakLocations = maximumLocation;

        leftMinimum = min( ...
            analysisEnvelopeZ( ...
            1:maximumLocation), ...
            [], ...
            'omitnan');

        rightMinimum = min( ...
            analysisEnvelopeZ( ...
            maximumLocation:end), ...
            [], ...
            'omitnan');

        fallbackContour = max( ...
            leftMinimum, ...
            rightMinimum);

        fallbackProminence = ...
            maximumEnvelopeZ - ...
            fallbackContour;

        allPeakProminences = ...
            fallbackProminence;

        widthLevel = ...
            maximumEnvelopeZ - ...
            0.5 * max( ...
            fallbackProminence, 0);

        leftWidthIndex = ...
            maximumLocation;

        while leftWidthIndex > 1 && ...
                analysisEnvelopeZ( ...
                leftWidthIndex) > widthLevel
            leftWidthIndex = ...
                leftWidthIndex - 1;
        end

        rightWidthIndex = ...
            maximumLocation;

        while rightWidthIndex < ...
                numel(analysisEnvelopeZ) && ...
                analysisEnvelopeZ( ...
                rightWidthIndex) > widthLevel
            rightWidthIndex = ...
                rightWidthIndex + 1;
        end

        allPeakWidths = ...
            rightWidthIndex - ...
            leftWidthIndex;
    end

    allPeakTimesSec = ...
        analysisTimeSec(allPeakLocations);

    [sortedPeakValues, peakSortOrder] = ...
        sort(allPeakValues, 'descend');

    sortedPeakLocations = ...
        allPeakLocations(peakSortOrder);

    sortedPeakWidths = ...
        allPeakWidths(peakSortOrder);

    sortedPeakProminences = ...
        allPeakProminences(peakSortOrder);

    sortedPeakTimesSec = ...
        allPeakTimesSec(peakSortOrder);

    % Anchor the parent event to the qualifying envelope peak nearest
    % the original detector timestamp. A larger neighbouring event must
    % not steal the parent event simply because it lies inside the broad
    % display window.
    [~, mainSelectionIndex] = min(abs(allPeakTimesSec));

    mainPeakValue = ...
        allPeakValues(mainSelectionIndex);

    mainPeakLocationInAnalysis = ...
        allPeakLocations(mainSelectionIndex);

    mainPeakGlobalRow = ...
        analysisRows(mainPeakLocationInAnalysis);

    mainPeakTimeSec = ...
        relativeTimeSec(mainPeakGlobalRow);

    refinedLocalPeakZ(rr) = mainPeakValue;
    refinedMainPeakOffsetMs(rr) = ...
        mainPeakTimeSec * 1000;

    if ~isempty(allPeakProminences)
        refinedMainPeakProminenceZ(rr) = ...
            allPeakProminences(mainSelectionIndex);
    end

    if ~isempty(allPeakWidths) && ...
            isfinite(allPeakWidths(mainSelectionIndex))
        refinedMainPeakWidthMs(rr) = ...
            allPeakWidths(mainSelectionIndex) / FsDs * 1000;
    end

    nIndependentEnvelopePeaksZ2(rr) = ...
        sum(allPeakValues >= peakHeightZ);

    strongMask = ...
        allPeakValues >= strongPeakHeightZ;

    if ~isempty(allPeakProminences)
        strongMask = ...
            strongMask & ...
            allPeakProminences >= ...
                strongPeakProminenceZ;
    end

    nStrongEnvelopePeaksZ3(rr) = ...
        sum(strongMask);

    if numel(allPeakValues) >= 2
        otherPeakIndices = setdiff( ...
            (1:numel(allPeakValues))', ...
            mainSelectionIndex);

        [secondEnvelopePeakZ(rr), ...
            secondRelativeIndex] = max( ...
            allPeakValues(otherPeakIndices));

        secondPeakIndex = ...
            otherPeakIndices(secondRelativeIndex);

        secondToFirstEnvelopePeakRatio(rr) = ...
            secondEnvelopePeakZ(rr) / ...
            max(mainPeakValue, eps);

        allPeakTimesSortedChronologically = ...
            sort(allPeakTimesSec);

        nearestIndependentPeakSeparationMs(rr) = ...
            min(diff( ...
            allPeakTimesSortedChronologically)) * 1000;

        valleyFractions = nan( ...
            numel(allPeakTimesSortedChronologically)-1, 1);

        for pp = 1: ...
                numel(allPeakTimesSortedChronologically)-1
            leftTime = ...
                allPeakTimesSortedChronologically(pp);

            rightTime = ...
                allPeakTimesSortedChronologically(pp+1);

            betweenMask = ...
                analysisTimeSec >= leftTime & ...
                analysisTimeSec <= rightTime;

            if any(betweenMask)
                valleyValue = ...
                    min(analysisEnvelopeZ(betweenMask));

                leftValue = ...
                    max(analysisEnvelopeZ( ...
                    abs(analysisTimeSec-leftTime) <= ...
                    1/FsDs));

                rightValue = ...
                    max(analysisEnvelopeZ( ...
                    abs(analysisTimeSec-rightTime) <= ...
                    1/FsDs));

                valleyFractions(pp) = ...
                    valleyValue / ...
                    max(min(leftValue, rightValue), eps);
            end
        end

        minimumInterPeakValleyFraction(rr) = ...
            min(valleyFractions, [], 'omitnan');
    else
        secondEnvelopePeakZ(rr) = 0;
        secondToFirstEnvelopePeakRatio(rr) = 0;
        nearestIndependentPeakSeparationMs(rr) = NaN;
        minimumInterPeakValleyFraction(rr) = NaN;
    end

    % Refined main-event boundaries around the largest envelope peak.
    leftAnalysisIndex = mainPeakLocationInAnalysis;
    rightAnalysisIndex = mainPeakLocationInAnalysis;

    while leftAnalysisIndex > 1 && ...
            analysisEnvelopeZ(leftAnalysisIndex) > ...
            boundaryZ
        leftAnalysisIndex = ...
            leftAnalysisIndex - 1;
    end

    while rightAnalysisIndex < ...
            numel(analysisEnvelopeZ) && ...
            analysisEnvelopeZ(rightAnalysisIndex) > ...
            boundaryZ
        rightAnalysisIndex = ...
            rightAnalysisIndex + 1;
    end

    leftBoundaryFound = ...
        leftAnalysisIndex > 1 || ...
        analysisEnvelopeZ(1) <= boundaryZ;

    rightBoundaryFound = ...
        rightAnalysisIndex < numel(analysisEnvelopeZ) || ...
        analysisEnvelopeZ(end) <= boundaryZ;

    refinedBoundaryFoundBothSides(rr) = ...
        leftBoundaryFound && rightBoundaryFound;

    refinedStartTimeSec = ...
        analysisTimeSec(leftAnalysisIndex);

    refinedEndTimeSec = ...
        analysisTimeSec(rightAnalysisIndex);

    refinedStartUs(rr) = ...
        peakUs + refinedStartTimeSec * 1e6;

    refinedEndUs(rr) = ...
        peakUs + refinedEndTimeSec * 1e6;

    refinedDurationS(rr) = ...
        refinedEndTimeSec - refinedStartTimeSec;

    % Decide whether the event contains separable high-frequency packets.
    hasSeparatedPeaks = false;

    if numel(sortedPeakValues) >= 2
        hasSeparatedPeaks = ...
            secondToFirstEnvelopePeakRatio(rr) >= ...
                splitSecondToFirstRatioMinimum && ...
            nearestIndependentPeakSeparationMs(rr) >= ...
                minimumSplitSeparationSec * 1000;

        if isfinite(minimumInterPeakValleyFraction(rr))
            hasSeparatedPeaks = ...
                hasSeparatedPeaks && ...
                minimumInterPeakValleyFraction(rr) <= ...
                    splitValleyFractionMaximum;
        end
    end

    splitRecommended(rr) = hasSeparatedPeaks;

    % Child event suggestions use all peaks satisfying z >= 2 and
    % prominence >= 0.75, constrained by midpoints to adjacent peaks.
    if splitRecommended(rr)
        [chronologicalPeakTimes, chronologicalOrder] = ...
            sort(allPeakTimesSec);

        chronologicalPeakValues = ...
            allPeakValues(chronologicalOrder);

        chronologicalPeakProms = ...
            allPeakProminences(chronologicalOrder);

        chronologicalPeakWidths = ...
            allPeakWidths(chronologicalOrder);

        nRecommendedChildEvents(rr) = ...
            numel(chronologicalPeakTimes);

        for pp = 1:numel(chronologicalPeakTimes)
            childPeakTimeSec = ...
                chronologicalPeakTimes(pp);

            [~, childPeakAnalysisIndex] = ...
                min(abs( ...
                analysisTimeSec - childPeakTimeSec));

            childLeftIndex = ...
                childPeakAnalysisIndex;

            childRightIndex = ...
                childPeakAnalysisIndex;

            while childLeftIndex > 1 && ...
                    analysisEnvelopeZ(childLeftIndex) > ...
                    boundaryZ
                childLeftIndex = childLeftIndex - 1;
            end

            while childRightIndex < ...
                    numel(analysisEnvelopeZ) && ...
                    analysisEnvelopeZ(childRightIndex) > ...
                    boundaryZ
                childRightIndex = childRightIndex + 1;
            end

            if pp > 1
                leftMidpointSec = ...
                    0.5 * ( ...
                    chronologicalPeakTimes(pp-1) + ...
                    chronologicalPeakTimes(pp));

                [~, midpointIndex] = ...
                    min(abs( ...
                    analysisTimeSec - ...
                    leftMidpointSec));

                childLeftIndex = ...
                    max(childLeftIndex, midpointIndex);
            end

            if pp < numel(chronologicalPeakTimes)
                rightMidpointSec = ...
                    0.5 * ( ...
                    chronologicalPeakTimes(pp) + ...
                    chronologicalPeakTimes(pp+1));

                [~, midpointIndex] = ...
                    min(abs( ...
                    analysisTimeSec - ...
                    rightMidpointSec));

                childRightIndex = ...
                    min(childRightIndex, midpointIndex);
            end

            childStartTimeSec = ...
                analysisTimeSec(childLeftIndex);

            childEndTimeSec = ...
                analysisTimeSec(childRightIndex);

            childParentBlindID(end+1,1) = ...
                string(blindID); %#ok<SAGROW>

            childIndex(end+1,1) = pp; %#ok<SAGROW>

            childPeakUs(end+1,1) = ...
                peakUs + childPeakTimeSec * 1e6; %#ok<SAGROW>

            childStartUs(end+1,1) = ...
                peakUs + childStartTimeSec * 1e6; %#ok<SAGROW>

            childEndUs(end+1,1) = ...
                peakUs + childEndTimeSec * 1e6; %#ok<SAGROW>

            childDurationS(end+1,1) = ...
                childEndTimeSec - ...
                childStartTimeSec; %#ok<SAGROW>

            childPeakZ(end+1,1) = ...
                chronologicalPeakValues(pp); %#ok<SAGROW>

            if ~isempty(chronologicalPeakProms)
                childProminenceZ(end+1,1) = ...
                    chronologicalPeakProms(pp); %#ok<SAGROW>
            else
                childProminenceZ(end+1,1) = ...
                    NaN; %#ok<SAGROW>
            end

            if ~isempty(chronologicalPeakWidths)
                childWidthMs(end+1,1) = ...
                    chronologicalPeakWidths(pp) / ...
                    FsDs * 1000; %#ok<SAGROW>
            else
                childWidthMs(end+1,1) = ...
                    NaN; %#ok<SAGROW>
            end

            childRelativePeakTimeMs(end+1,1) = ...
                childPeakTimeSec * 1000; %#ok<SAGROW>

            childPeakRank(end+1,1) = ...
                find(peakSortOrder == ...
                chronologicalOrder(pp), 1); %#ok<SAGROW>
        end
    end

    % Spectral features use a compact event-centred window.
    spectralMask = ...
        abs(relativeTimeSec - mainPeakTimeSec) <= ...
            spectralHalfWindowSec;

    spectralRows = find(spectralMask);

    if numel(spectralRows) >= 64
        spectralSignal = ...
            lfpDs(spectralRows);

        spectralSignal = ...
            spectralSignal - ...
            mean(spectralSignal, 'omitnan');

        nfft = max(2048, ...
            2^nextpow2(numel(spectralSignal)));

        try
            spectralWindow = ...
                hann(numel(spectralSignal));

            [powerSpectrum, frequencyHz] = ...
                pwelch( ...
                    spectralSignal, ...
                    spectralWindow, ...
                    0, ...
                    nfft, ...
                    FsDs);

            spectrumDb = ...
                10 * log10(powerSpectrum + eps);

            searchMask = ...
                frequencyHz >= ...
                    spectralPeakRangeHz(1) & ...
                frequencyHz <= ...
                    spectralPeakRangeHz(2);

            searchFrequency = ...
                frequencyHz(searchMask);

            searchDb = spectrumDb(searchMask);

            try
                [spectralPeaksDb, ...
                    spectralPeakLocations, ...
                    ~, ...
                    spectralProminencesDb] = ...
                    findpeaks(searchDb);

                if ~isempty(spectralPeaksDb)
                    [~, strongestSpectralIndex] = ...
                        max(spectralProminencesDb);

                    selectedSpectralPeakDb = ...
                        spectralPeaksDb( ...
                        strongestSpectralIndex);

                    selectedSpectralPeakFrequency = ...
                        searchFrequency( ...
                        spectralPeakLocations( ...
                        strongestSpectralIndex));

                    selectedSpectralProminenceDb = ...
                        spectralProminencesDb( ...
                        strongestSpectralIndex);
                else
                    [selectedSpectralPeakDb, ...
                        maximumSpectralIndex] = ...
                        max(searchDb);

                    selectedSpectralPeakFrequency = ...
                        searchFrequency( ...
                        maximumSpectralIndex);

                    selectedSpectralProminenceDb = ...
                        selectedSpectralPeakDb - ...
                        median(searchDb, 'omitnan');
                end
            catch
                [selectedSpectralPeakDb, ...
                    maximumSpectralIndex] = ...
                    max(searchDb);

                selectedSpectralPeakFrequency = ...
                    searchFrequency( ...
                    maximumSpectralIndex);

                selectedSpectralProminenceDb = ...
                    selectedSpectralPeakDb - ...
                    median(searchDb, 'omitnan');
            end

            spectralPeakHz120To250(rr) = ...
                selectedSpectralPeakFrequency;

            spectralPeakProminenceDb(rr) = ...
                selectedSpectralProminenceDb;

            wideSearchMask = ...
                frequencyHz >= wideHighBandHz(1) & ...
                frequencyHz <= wideHighBandHz(2);

            spectralPeakToMedian80To300Db(rr) = ...
                selectedSpectralPeakDb - ...
                median( ...
                spectrumDb(wideSearchMask), ...
                'omitnan');

            spectralPeakAtBoundary(rr) = ...
                selectedSpectralPeakFrequency <= ...
                    spectralPeakRangeHz(1) + ...
                    spectralInteriorMarginHz || ...
                selectedSpectralPeakFrequency >= ...
                    spectralPeakRangeHz(2) - ...
                    spectralInteriorMarginHz;

            spectralPeakIsInterior(rr) = ...
                ~spectralPeakAtBoundary(rr) && ...
                selectedSpectralProminenceDb >= ...
                    spectralProminenceMinimumForInteriorFlagDb;

            rippleMask = ...
                frequencyHz >= rippleBandHz(1) & ...
                frequencyHz <= rippleBandHz(2);

            wideHighMask = ...
                frequencyHz >= wideHighBandHz(1) & ...
                frequencyHz <= wideHighBandHz(2);

            upperHighMask = ...
                frequencyHz >= ...
                    upperHighBandEffectiveHz(1) & ...
                frequencyHz <= ...
                    upperHighBandEffectiveHz(2);

            fullHighMask = ...
                frequencyHz >= wideHighBandHz(1) & ...
                frequencyHz <= ...
                    upperHighBandEffectiveHz(2);

            if any(rippleMask)
                ripplePower120To250(rr) = ...
                    trapz( ...
                    frequencyHz(rippleMask), ...
                    powerSpectrum(rippleMask));
            end

            if any(wideHighMask)
                wideHighPower80To300(rr) = ...
                    trapz( ...
                    frequencyHz(wideHighMask), ...
                    powerSpectrum(wideHighMask));

                positiveWidePower = ...
                    powerSpectrum(wideHighMask);

                positiveWidePower = ...
                    positiveWidePower( ...
                    isfinite(positiveWidePower) & ...
                    positiveWidePower > 0);

                if ~isempty(positiveWidePower)
                    spectralFlatness80To300(rr) = ...
                        exp(mean(log(positiveWidePower))) / ...
                        mean(positiveWidePower);
                end
            end

            if any(upperHighMask)
                upperHighPower250To450(rr) = ...
                    trapz( ...
                    frequencyHz(upperHighMask), ...
                    powerSpectrum(upperHighMask));
            end

            if isfinite(ripplePower120To250(rr)) && ...
                    isfinite(wideHighPower80To300(rr)) && ...
                    wideHighPower80To300(rr) > 0
                rippleFractionOf80To300(rr) = ...
                    ripplePower120To250(rr) / ...
                    wideHighPower80To300(rr);
            end

            if any(fullHighMask)
                fullHighPower = ...
                    trapz( ...
                    frequencyHz(fullHighMask), ...
                    powerSpectrum(fullHighMask));

                outsideRipplePower = ...
                    max(0, fullHighPower - ...
                    ripplePower120To250(rr));

                if isfinite(fullHighPower) && ...
                        fullHighPower > 0
                    outsideRippleFraction80To450(rr) = ...
                        outsideRipplePower / ...
                        fullHighPower;
                end
            end

            if isfinite(ripplePower120To250(rr)) && ...
                    isfinite(upperHighPower250To450(rr)) && ...
                    upperHighPower250To450(rr) > 0
                rippleVsUpperHighDb(rr) = ...
                    10 * log10( ...
                    ripplePower120To250(rr) / ...
                    upperHighPower250To450(rr));
            end
        catch
        end
    end

    % Broadband transient and ringing-context features.
    sharpMask = ...
        abs(relativeTimeSec - mainPeakTimeSec) <= ...
            sharpFeatureHalfWindowSec;

    if any(sharpMask)
        localRaw = lfpDs(sharpMask);
        localSharp = sharpFiltered(sharpMask);
        localRipple = rippleFiltered(sharpMask);

        refinedRawPeakToPeak(rr) = ...
            max(localRaw) - min(localRaw);

        refinedSharpWavePeakAbs(rr) = ...
            max(abs(localSharp));

        ripplePeakToPeak = ...
            max(localRipple) - min(localRipple);

        rawToRipplePeakToPeakRatio(rr) = ...
            refinedRawPeakToPeak(rr) / ...
            max(ripplePeakToPeak, eps);

        rawDerivative = [0; diff(lfpDs)] .* FsDs;

        derivativeBaseline = ...
            rawDerivative(baselineMask);

        derivativeMedian = ...
            median(derivativeBaseline, 'omitnan');

        derivativeMad = ...
            median(abs( ...
            derivativeBaseline - derivativeMedian), ...
            'omitnan');

        derivativeSigma = ...
            1.4826 * derivativeMad;

        if ~isfinite(derivativeSigma) || ...
                derivativeSigma <= 0
            derivativeSigma = ...
                std(derivativeBaseline, 'omitnan');
        end

        if ~isfinite(derivativeSigma) || ...
                derivativeSigma <= 0
            derivativeSigma = 1;
        end

        derivativeRobustZ = ...
            abs( ...
            (rawDerivative - derivativeMedian) ./ ...
            derivativeSigma);

        localDerivativeZ = ...
            derivativeRobustZ(sharpMask);

        localSharpRows = find(sharpMask);

        [rawDerivativePeakRobustZ(rr), ...
            derivativeLocalIndex] = ...
            max(localDerivativeZ);

        derivativeGlobalRow = ...
            localSharpRows(derivativeLocalIndex);

        derivativePeakTimeSec = ...
            relativeTimeSec(derivativeGlobalRow);

        derivativeToEnvelopePeakOffsetMs(rr) = ...
            abs( ...
            derivativePeakTimeSec - ...
            mainPeakTimeSec) * 1000;

        symmetryHalfWindowSec = ...
            min(0.10, ...
            max(0.02, ...
            refinedDurationS(rr)));

        preSymmetryMask = ...
            relativeTimeSec >= ...
                mainPeakTimeSec - ...
                symmetryHalfWindowSec & ...
            relativeTimeSec < mainPeakTimeSec;

        postSymmetryMask = ...
            relativeTimeSec > mainPeakTimeSec & ...
            relativeTimeSec <= ...
                mainPeakTimeSec + ...
                symmetryHalfWindowSec;

        preArea = ...
            trapz( ...
            relativeTimeSec(preSymmetryMask), ...
            rippleEnvelope(preSymmetryMask));

        postArea = ...
            trapz( ...
            relativeTimeSec(postSymmetryMask), ...
            rippleEnvelope(postSymmetryMask));

        rippleEnvelopeSymmetry(rr) = ...
            1 - abs(preArea - postArea) / ...
            max(preArea + postArea, eps);

        alignmentWeight = ...
            exp( ...
            -derivativeToEnvelopePeakOffsetMs(rr) / 15);

        filterRingingRiskIndex(rr) = ...
            rawDerivativePeakRobustZ(rr) * ...
            alignmentWeight * ...
            max(rippleEnvelopeSymmetry(rr), 0);

        if isfinite( ...
                outsideRippleFraction80To450(rr))
            broadbandTransientIndex(rr) = ...
                rawDerivativePeakRobustZ(rr) * ...
                outsideRippleFraction80To450(rr);
        else
            broadbandTransientIndex(rr) = ...
                rawDerivativePeakRobustZ(rr);
        end
    end

    refinedLoadSucceeded(rr) = true;
    effectiveSamplingRateHz(rr) = FsDs;

    %% Diagnostic figure

    if generateAllDiagnosticFigures
        figurePath = fullfile( ...
            figureFolder, ...
            [blindID '_refined_morphology.png']);

        diagnosticFigureFile(rr) = ...
            string(figurePath);

        fig = figure( ...
            'Visible', 'off', ...
            'Color', 'w', ...
            'Position', [70 40 1450 1250]);

        tl = tiledlayout( ...
            7, 1, ...
            'TileSpacing', 'compact', ...
            'Padding', 'compact');

        visibleMask = ...
            abs(relativeTimeSec) <= ...
                analysisHalfWindowSec;

        nexttile
        plot( ...
            relativeTimeSec(visibleMask), ...
            lfpDs(visibleMask), ...
            'k', ...
            'LineWidth', 0.8);

        hold on
        xline(0, 'r--', 'Detector peak');
        xline( ...
            (detectorStartUs-peakUs)/1e6, ...
            ':', ...
            'Detector start');
        xline( ...
            (detectorEndUs-peakUs)/1e6, ...
            ':', ...
            'Detector end');
        xline( ...
            (refinedStartUs(rr)-peakUs)/1e6, ...
            'b--', ...
            'Refined start');
        xline( ...
            (refinedEndUs(rr)-peakUs)/1e6, ...
            'b--', ...
            'Refined end');
        hold off

        xlim([ ...
            -analysisHalfWindowSec, ...
            analysisHalfWindowSec]);

        ylabel('Raw LFP');
        title(sprintf( ...
            '%s refined morphology | blinded class: %s', ...
            blindID, ...
            T.primaryClassification(rr)), ...
            'Interpreter', 'none');
        grid on

        nexttile
        plot( ...
            relativeTimeSec(visibleMask), ...
            rippleFiltered(visibleMask), ...
            'k', ...
            'LineWidth', 0.8);
        hold on
        xline(0, 'r--');
        hold off
        xlim([ ...
            -analysisHalfWindowSec, ...
            analysisHalfWindowSec]);
        ylabel('120-250 Hz');
        grid on

        nexttile
        plot( ...
            analysisTimeSec, ...
            analysisEnvelopeZ, ...
            'k', ...
            'LineWidth', 1);
        hold on

        scatter( ...
            allPeakTimesSec, ...
            allPeakValues, ...
            40, ...
            'filled');

        yline(peakHeightZ, '--', 'Peak threshold');
        yline(boundaryZ, ':', 'Boundary z');
        xline(0, 'r--');
        xline( ...
            mainPeakTimeSec, ...
            'b--', ...
            'Main envelope peak');
        hold off

        xlim([ ...
            -analysisHalfWindowSec, ...
            analysisHalfWindowSec]);
        ylabel('Envelope robust z');
        grid on

        nexttile
        rawDerivative = [0; diff(lfpDs)] .* FsDs;

        derivativeBaseline = ...
            rawDerivative(baselineMask);

        derivativeMedian = ...
            median(derivativeBaseline, 'omitnan');

        derivativeMad = ...
            median(abs( ...
            derivativeBaseline - derivativeMedian), ...
            'omitnan');

        derivativeSigma = ...
            1.4826 * derivativeMad;

        if ~isfinite(derivativeSigma) || ...
                derivativeSigma <= 0
            derivativeSigma = ...
                std(derivativeBaseline, 'omitnan');
        end

        if ~isfinite(derivativeSigma) || ...
                derivativeSigma <= 0
            derivativeSigma = 1;
        end

        derivativeRobustZ = ...
            abs( ...
            (rawDerivative - derivativeMedian) ./ ...
            derivativeSigma);

        plot( ...
            relativeTimeSec(visibleMask), ...
            derivativeRobustZ(visibleMask), ...
            'Color', [0.35 0.35 0.35]);

        hold on
        xline(0, 'r--');
        xline(mainPeakTimeSec, 'b--');
        hold off
        xlim([ ...
            -analysisHalfWindowSec, ...
            analysisHalfWindowSec]);
        ylabel('|dLFP/dt| robust z');
        grid on

        nexttile
        if exist('frequencyHz', 'var') && ...
                exist('spectrumDb', 'var') && ...
                numel(frequencyHz) == numel(spectrumDb)
            plot(frequencyHz, spectrumDb, 'k');
            hold on
            xline(120, '--');
            xline(250, '--');

            if isfinite(spectralPeakHz120To250(rr))
                xline( ...
                    spectralPeakHz120To250(rr), ...
                    'r-', ...
                    'Selected spectral peak');
            end

            hold off
            xlim([60 min(450, FsDs/2-2)]);
            ylabel('PSD (dB)');
            xlabel('Frequency (Hz)');
            grid on
        else
            axis off
            text(0.5,0.5, ...
                'Spectrum unavailable', ...
                'HorizontalAlignment','center');
        end

        nexttile
        spectrogramMask = ...
